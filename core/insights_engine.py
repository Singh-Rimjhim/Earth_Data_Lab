"""
Insights Engine for Earth Data Lab.
Generates research insights distinguishing empirical observations from causal attribution.
Adheres strictly to scientific methodology: statistical trends indicate WHAT happened,
while physical attribution requires climate models (e.g. CMIP6, IPCC AR6).
"""

import pandas as pd
import numpy as np
from typing import Dict, Any, List
from core.statistics_engine import calculate_linear_trend, calculate_summary_statistics, get_warmest_years


def generate_research_insights(df: pd.DataFrame, dataset_meta: Dict[str, Any]) -> Dict[str, Any]:
    """
    Generates structured scientific insights from the active dataset.
    Explicitly separates 'Observed Pattern' from 'Causal Explanation / Attribution'.
    """
    if df is None or len(df) < 5:
        return {
            "insights": [],
            "summary": "Insufficient data to generate scientific insights."
        }

    is_synthetic = dataset_meta.get("is_synthetic", False)
    min_year = int(df['year'].min())
    max_year = int(df['year'].max())

    # Full period trend
    overall_trend = calculate_linear_trend(df)
    warmest_5 = get_warmest_years(df, 5)
    
    # Check for post-1970 acceleration if data covers that range
    has_post_1970 = (min_year <= 1970 and max_year >= 2010)
    post_1970_insight = None
    if has_post_1970:
        df_post_1970 = df[df['year'] >= 1970]
        df_pre_1970 = df[df['year'] < 1970]
        trend_post = calculate_linear_trend(df_post_1970)
        trend_pre = calculate_linear_trend(df_pre_1970) if len(df_pre_1970) >= 2 else None
        
        post_1970_insight = {
            "title": "Post-1970 Warming Acceleration",
            "type": "acceleration",
            "observed_pattern": (
                f"From 1970 to {max_year}, the observed warming rate is "
                f"+{trend_post['warming_rate_per_decade']:.3f}°C/decade (R² = {trend_post['r_squared']:.2f}). "
                + (f"In contrast, the 1880–1969 period exhibited a rate of +{trend_pre['warming_rate_per_decade']:.3f}°C/decade." if trend_pre else "")
            ),
            "causal_explanation": (
                "Empirical records alone do not demonstrate causality. In scientific literature (e.g., IPCC AR6 WGI Chapter 3), "
                "this acceleration is attributed to greenhouse gas radiative forcing overtaking the cooling effect of sulfate aerosols."
                if not is_synthetic else
                "SIMULATION NOTE: This trend is mathematically generated by synthetic parameters, not physical climate dynamics."
            ),
            "confidence_level": "High (Empirical Fit R² = " + str(trend_post['r_squared']) + ")" if not is_synthetic else "Synthetic (Simulated)"
        }

    # Clustering of warmest years
    warmest_years_list = [w['year'] for w in warmest_5]
    recent_warmest_count = sum(1 for y in warmest_years_list if y >= 2010)
    
    clustering_insight = {
        "title": "Concentration of Record High Temperatures",
        "type": "records",
        "observed_pattern": (
            f"The top warmest years on record are {', '.join(str(w['year']) + ' (' + ('+' if w['anomaly']>0 else '') + str(w['anomaly']) + '°C)' for w in warmest_5[:3])}. "
            f"{recent_warmest_count} of the top 5 warmest years have occurred since 2010."
        ),
        "causal_explanation": (
            "Statistically, if global temperatures were stationary, record highs would be distributed uniformly across the 140+ year span. "
            "Their temporal clustering in recent decades is strong empirical evidence of a non-stationary upward shift in the global temperature distribution."
            if not is_synthetic else
            "Synthetic data generation incorporates a deliberate upward baseline shift."
        ),
        "confidence_level": "Very High (Observational Consensus across NOAA, NASA, Met Office)" if not is_synthetic else "Synthetic (Simulated)"
    }

    # Interannual variability & natural cycles
    variability_insight = {
        "title": "Interannual Variability vs Long-Term Trend",
        "type": "variability",
        "observed_pattern": (
            f"Year-to-year fluctuations show a standard deviation of ±{df['annual_anomaly'].std():.2f}°C around the mean. "
            f"Individual years may be cooler than preceding years despite the overall +{overall_trend['warming_rate_per_decade']:.3f}°C/decade trend."
        ),
        "causal_explanation": (
            "Short-term annual fluctuations reflect coupled ocean-atmosphere oscillations such as the El Niño-Southern Oscillation (ENSO), "
            "volcanic aerosol scattering (e.g., Mt. Pinatubo 1991), and solar irradiance cycles, superimposed on decadal climate forcing."
            if not is_synthetic else
            "Synthetic model uses a sinusoidal cycle with period T=4.5 years and Gaussian noise."
        ),
        "confidence_level": "Robustly Documented Physical Phenomenon" if not is_synthetic else "Synthetic Simulation"
    }

    insights_list = [clustering_insight]
    if post_1970_insight:
        insights_list.insert(0, post_1970_insight)
    insights_list.append(variability_insight)

    return {
        "overall_warming_rate_per_decade": overall_trend['warming_rate_per_decade'],
        "r_squared": overall_trend['r_squared'],
        "sample_span": f"{min_year}–{max_year}",
        "dataset_type": "Synthetic Demonstration" if is_synthetic else "Observed Instrument Record",
        "insights": insights_list
    }
